#!/usr/bin/env python3
"""Generate resized game assets, Defold atlases, asset map and SFX.

Source art in /assets is never modified. Everything is written to
/main/generated, /main/atlases and /assets/sounds.
"""

import math
import os
import random
import shutil
import struct
import subprocess
import wave
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ASSETS = ROOT / "assets"
CARDS_SRC = ASSETS / "cards"
MONSTERS_SRC = ASSETS / "monsters"
BOARD_SRC = ASSETS / "board.png"
GEN = ROOT / "main" / "generated"
ATLAS = ROOT / "main" / "atlases"
SOUNDS = ASSETS / "sounds"

CARD_W, CARD_H = 406, 606
MONSTER_MAX = 600
CARD_GROUP = 12
MONSTER_GROUP = 6


def run(cmd):
    subprocess.run(cmd, check=True, stdout=subprocess.DEVNULL)


def image_size(path):
    out = subprocess.check_output(
        ["identify", "-format", "%w %h", str(path)], text=True
    ).strip()
    w, h = out.split()
    return int(w), int(h)


def prepare_images():
    for d in (GEN / "cards", GEN / "monsters", GEN / "ui"):
        d.mkdir(parents=True, exist_ok=True)

    card_files = sorted(CARDS_SRC.glob("*.png"), key=lambda p: p.stem.lower())
    for src in card_files:
        dst = GEN / "cards" / src.name
        run(["convert", str(src), "-background", "none", "-resize", f"{CARD_W}x{CARD_H}!", "-strip", str(dst)])

    monster_files = sorted(MONSTERS_SRC.glob("*.png"), key=lambda p: p.stem.lower())
    for src in monster_files:
        dst = GEN / "monsters" / src.name
        run(["convert", str(src), "-background", "none", "-resize", f"{MONSTER_MAX}x{MONSTER_MAX}", "-strip", str(dst)])

    run(["convert", str(BOARD_SRC), "-resize", "1080x1920!", "-strip", str(GEN / "ui" / "board.png")])

    return card_files, monster_files


def write_atlas(path, image_paths):
    lines = []
    for p in image_paths:
        lines.append("images {")
        lines.append(f'  image: "{p}"')
        lines.append("}")
    lines.extend([
        "margin: 0",
        "extrude_borders: 2",
        "inner_padding: 0",
        "",
    ])
    path.write_text("\n".join(lines), encoding="utf-8")


def prepare_atlases(card_files, monster_files):
    ATLAS.mkdir(parents=True, exist_ok=True)
    card_groups = {}
    for i in range(0, len(card_files), CARD_GROUP):
        name = f"cards_{i // CARD_GROUP + 1}"
        group = card_files[i:i + CARD_GROUP]
        paths = [f"/main/generated/cards/{p.name}" for p in group]
        write_atlas(ATLAS / f"{name}.atlas", paths)
        card_groups[name] = group

    monster_groups = {}
    for i in range(0, len(monster_files), MONSTER_GROUP):
        name = f"monsters_{i // MONSTER_GROUP + 1}"
        group = monster_files[i:i + MONSTER_GROUP]
        paths = [f"/main/generated/monsters/{p.name}" for p in group]
        write_atlas(ATLAS / f"{name}.atlas", paths)
        monster_groups[name] = group

    write_atlas(ATLAS / "ui.atlas", ["/main/generated/ui/board.png"])
    return card_groups, monster_groups


def write_asset_map(card_groups, monster_groups):
    lines = ["-- Generated by tools/prepare_assets.py. Do not edit by hand.", "return {", "  cards = {"]
    for atlas_name, group in card_groups.items():
        for p in group:
            lines.append(
                f'    {p.stem} = {{ atlas = "{atlas_name}", anim = "{p.stem}" }},'
            )
    lines.append("  },")
    lines.append("  monsters = {")
    for atlas_name, group in monster_groups.items():
        for p in group:
            w, h = image_size(GEN / "monsters" / p.name)
            lines.append(
                f'    {p.stem} = {{ atlas = "{atlas_name}", anim = "{p.stem}", w = {w}, h = {h} }},'
            )
    lines.append("  },")
    lines.append('  board = { atlas = "ui", anim = "board" },')
    lines.append("}")
    (ROOT / "scripts" / "data" / "asset_map.lua").write_text(
        "\n".join(lines) + "\n", encoding="utf-8"
    )


def synth():
    SOUNDS.mkdir(parents=True, exist_ok=True)
    sr = 22050

    def write_wav(name, samples):
        path = SOUNDS / f"{name}.wav"
        with wave.open(str(path), "wb") as f:
            f.setnchannels(1)
            f.setsampwidth(2)
            f.setframerate(sr)
            data = b"".join(
                struct.pack("<h", max(-32767, min(32767, int(s * 32767))))
                for s in samples
            )
            f.writeframes(data)

    def env(i, n, attack=0.01, release=0.35):
        t = i / sr
        total = n / sr
        a = min(1.0, t / max(attack, 1e-6))
        r = min(1.0, max(0.0, (total - t) / max(release, 1e-6)))
        return a * r

    def tone(freq, dur, vol=0.35, harmonics=(1.0,), noise=0.0, sweep=0.0):
        n = int(sr * dur)
        out = []
        rng = random.Random(int(freq * 1000 + dur * 100))
        phase = 0.0
        for i in range(n):
            f = freq * (1.0 + sweep * (i / max(1, n)))
            phase += 2.0 * math.pi * f / sr
            v = sum(h * math.sin(phase * k) for k, h in enumerate(harmonics, 1))
            v /= sum(harmonics)
            if noise:
                v += (rng.random() * 2.0 - 1.0) * noise
            out.append(v * vol * env(i, n))
        return out

    def mix(*parts):
        n = max(len(p) for p in parts)
        out = []
        for i in range(n):
            out.append(sum(p[i] for p in parts if i < len(p)))
        return out

    write_wav("click", tone(880, 0.055, 0.20, (1.0, 0.3)))
    write_wav("draw", mix(tone(520, 0.09, 0.15, (1.0, 0.25)), tone(1300, 0.05, 0.06, noise=0.6)))
    write_wav("play", mix(tone(220, 0.14, 0.30, (1.0, 0.5, 0.25)), tone(110, 0.16, 0.18, (1.0, 0.4))))
    write_wav("hit", mix(tone(90, 0.26, 0.42, (1.0, 0.7, 0.4)), tone(180, 0.18, 0.20, noise=0.35, sweep=-0.5)))
    write_wav("burn", tone(480, 0.38, 0.28, (1.0, 0.5), noise=0.65, sweep=1.5))
    write_wav("win", mix(
        tone(392, 0.55, 0.22, (1.0, 0.4)),
        tone(523, 0.55, 0.18, (1.0, 0.4)),
        tone(659, 0.55, 0.16, (1.0, 0.4)),
    ))
    write_wav("lose", mix(
        tone(160, 0.85, 0.25, (1.0, 0.5, 0.2)),
        tone(120, 0.85, 0.22, (1.0, 0.5), sweep=-0.3),
    ))

    def loop_tone(freq, dur, vol=0.1, harmonics=(1.0,)):
        n = int(sr * dur)
        out = []
        phase = 0.0
        for i in range(n):
            t = i / sr
            phase += 2.0 * math.pi * freq / sr
            v = sum(h * math.sin(phase * k) for k, h in enumerate(harmonics, 1))
            v /= sum(harmonics)
            lfo = 0.6 + 0.4 * math.sin(2.0 * math.pi * 0.125 * t)
            out.append(v * vol * lfo)
        return out

    write_wav("bgm", mix(
        loop_tone(55, 8.0, 0.10, (1.0, 0.5, 0.25)),
        loop_tone(82.5, 8.0, 0.06, (1.0, 0.3)),
        loop_tone(110, 8.0, 0.035, (1.0, 0.2)),
    ))


def copy_font():
    font_dir = ROOT / "main" / "fonts"
    font_dir.mkdir(parents=True, exist_ok=True)
    target = font_dir / "VeraMono-Bold.ttf"
    if target.exists():
        return
    unpack = Path.home() / ".local/state/Defold/unpack"
    candidates = list(unpack.glob("*/builtins/builtins.zip"))
    if candidates:
        subprocess.run(
            [
                "unzip",
                "-o",
                str(candidates[0]),
                "builtins/fonts/vera_mo_bd.ttf",
                "-d",
                str(ROOT / ".tmp_font"),
            ],
            check=True,
            stdout=subprocess.DEVNULL,
        )
        shutil.copyfile(ROOT / ".tmp_font/builtins/fonts/vera_mo_bd.ttf", target)
        shutil.rmtree(ROOT / ".tmp_font", ignore_errors=True)


def main():
    card_files, monster_files = prepare_images()
    card_groups, monster_groups = prepare_atlases(card_files, monster_files)
    write_asset_map(card_groups, monster_groups)
    synth()
    copy_font()
    print(f"Prepared {len(card_files)} cards, {len(monster_files)} monsters, atlases and SFX.")


if __name__ == "__main__":
    main()
